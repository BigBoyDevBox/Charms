import AppKit
import Carbon.HIToolbox
import CharmsCore

/// Sends the chosen string to the source application, once.
@MainActor
final class InsertionService {
    private let diagnostics: DiagnosticsLog
    private var clipboardGuard = ClipboardRestoreGuard()
    private var savedClipboard: [[NSPasteboard.PasteboardType: Data]]?

    init(diagnostics: DiagnosticsLog) {
        self.diagnostics = diagnostics
    }

    enum Result {
        /// Input was sent. Whether the application acted on it is unknown.
        case dispatched
        /// Nothing was sent.
        case notStarted
    }

    func insert(_ text: String, processID: pid_t, backend: InsertionBackend, session: SessionID) -> Result {
        switch backend {
        case .unicodeEvents:
            return postUnicode(text, processID: processID)
        case .paste:
            return paste(text, processID: processID, session: session)
        }
    }

    /// Posts the string as keyboard events addressed to one process.
    ///
    /// Measured on macOS 27 in TextEdit: one key-down and key-up pair
    /// carrying the whole string inserts it exactly, replaces a selection,
    /// and is undone by a single Undo. The flags are cleared so that a
    /// modifier state left in the event source cannot turn the text into a
    /// shortcut.
    private func postUnicode(_ text: String, processID: pid_t) -> Result {
        let payloads = InsertionPolicy.eventPayloads(for: text)
        guard !payloads.isEmpty, let source = CGEventSource(stateID: .combinedSessionState) else { return .notStarted }
        var events: [CGEvent] = []
        for payload in payloads {
            guard let down = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: true),
                  let up = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: false) else {
                // Nothing has been posted yet, so nothing was sent.
                return .notStarted
            }
            down.flags = []
            up.flags = []
            down.keyboardSetUnicodeString(stringLength: payload.count, unicodeString: payload)
            up.keyboardSetUnicodeString(stringLength: payload.count, unicodeString: payload)
            events.append(down)
            events.append(up)
        }
        for event in events {
            event.postToPid(processID)
        }
        return .dispatched
    }

    /// Writes the string to the clipboard and sends Paste, then puts the
    /// previous clipboard back if nobody copied anything in the meantime.
    private func paste(_ text: String, processID: pid_t, session: SessionID) -> Result {
        guard clipboardGuard.canBegin else {
            // An earlier paste has not been settled yet. Starting another
            // could restore the wrong contents.
            diagnostics.record(.insertion, "paste-busy")
            return .notStarted
        }
        // Paste is Command plus whichever key types "v" with Command held
        // under the active layout, not a fixed position.
        let pasteKey = KeyLayout.keyCode(producing: "v", carbonModifiers: UInt32(cmdKey))
            ?? KeyLayout.keyCode(producing: "v", carbonModifiers: 0)
        guard let pasteKey, let source = CGEventSource(stateID: .combinedSessionState),
              let down = CGEvent(keyboardEventSource: source, virtualKey: pasteKey, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: pasteKey, keyDown: false) else {
            return .notStarted
        }

        let pasteboard = NSPasteboard.general
        savedClipboard = snapshot(pasteboard)
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Advisory markers that ask clipboard managers to skip this
        // temporary write. Cooperating tools honour them; nothing forces it.
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        guard pasteboard.writeObjects([item]) else {
            restore(pasteboard, expecting: nil)
            return .notStarted
        }
        clipboardGuard.begin(session: session, changeCountAfterWrite: pasteboard.changeCount)

        down.flags = .maskCommand
        up.flags = .maskCommand
        down.postToPid(processID)
        up.postToPid(processID)

        // There is no signal for "the application has read the clipboard".
        // The wait is a best effort; the change count below is the guard
        // that a newer copy is never overwritten.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.7) { [weak self] in
            MainActor.assumeIsolated { self?.restore(pasteboard, expecting: session) }
        }
        return .dispatched
    }

    /// The clipboard's current contents, or nil when they cannot be read
    /// without the system asking the user.
    private func snapshot(_ pasteboard: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]]? {
        if #available(macOS 15.4, *) {
            guard pasteboard.accessBehavior == .alwaysAllow else {
                diagnostics.record(.insertion, "clipboard-snapshot-skipped")
                return nil
            }
        }
        var items: [[NSPasteboard.PasteboardType: Data]] = []
        var total = 0
        for item in pasteboard.pasteboardItems ?? [] {
            var copy: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                copy[type] = data
            }
            items.append(copy)
        }
        // Holding a very large clipboard in memory to save one character's
        // detour is not worth it.
        return total <= 32 * 1024 * 1024 ? items : nil
    }

    private func restore(_ pasteboard: NSPasteboard, expecting session: SessionID?) {
        defer { savedClipboard = nil }
        if let session {
            guard clipboardGuard.resolve(session: session, currentChangeCount: pasteboard.changeCount) else {
                diagnostics.record(.insertion, "clipboard-kept-newer-copy")
                return
            }
        }
        guard let savedClipboard else { return }
        pasteboard.clearContents()
        let items = savedClipboard.map { saved -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in saved {
                item.setData(data, forType: type)
            }
            return item
        }
        if !items.isEmpty {
            pasteboard.writeObjects(items)
        }
        diagnostics.record(.insertion, "clipboard-restored")
    }

    /// An explicit Copy: the clipboard is meant to change.
    func copy(_ text: String) {
        // A pending restoration must not put older contents over this copy.
        clipboardGuard.abandon()
        savedClipboard = nil
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }
}

/// Reads whether the keys that could leak into the source are still down.
enum KeyState {
    static func current() -> ReleaseGate.Inputs {
        let state = CGEventSourceStateID.combinedSessionState
        let flags = CGEventSource.flagsState(state)
        let modifiers = !flags.intersection([.maskShift, .maskControl, .maskAlternate, .maskCommand]).isEmpty
        let commit = CGEventSource.keyState(state, key: CGKeyCode(kVK_Return))
            || CGEventSource.keyState(state, key: CGKeyCode(kVK_ANSI_KeypadEnter))
        let mouse = CGEventSource.buttonState(state, button: .left)
        return ReleaseGate.Inputs(modifiersDown: modifiers, commitKeyDown: commit, mouseButtonDown: mouse)
    }
}
